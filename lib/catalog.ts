export function getNiche(id: string | null | undefined) {
  if (!id) return undefined;
  return catalogNiches.find((niche) => niche.id === id);
}

export function isNicheId(value: unknown): value is string {
  return typeof value === "string" && catalogNiches.some((niche) => niche.id === value);
}
